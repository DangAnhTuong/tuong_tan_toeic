function lookupTranslation(text) {
  if (!text || typeof text !== 'string') return null;
  const clean = text.trim();
  if (MASTER_DICTIONARY[clean]) return MASTER_DICTIONARY[clean];
  if (MASTER_DICTIONARY[clean.toLowerCase()]) return MASTER_DICTIONARY[clean.toLowerCase()];

  // Strip trailing punctuation
  const stripped = clean.replace(/[.,!?;:]+$/, '');
  if (MASTER_DICTIONARY[stripped]) return MASTER_DICTIONARY[stripped];
  if (MASTER_DICTIONARY[stripped.toLowerCase()]) return MASTER_DICTIONARY[stripped.toLowerCase()];

  // Pure numbers or money
  if (/^[\$€£]?\d+([,\.]\d+)?%?$/.test(clean)) {
    return clean;
  }

  // Model codes or flight numbers (e.g. #4027, EVO160, F-12, TL0015)
  if (/^(#\d+|[A-Z]{1,4}[-\s]?\d{1,6}[A-Z]?|\d{1,4}[A-Z]{1,4})$/.test(clean)) {
    return clean;
  }

  return null;
}

